const fs = require("fs");
const path = require("path");

const {
  generateCloudflareImage,
} = require("./helpers/aiDesign/cloudflareClient");

const credentials = {
  accountId: process.env.CF_ACCOUNT_ID,
  apiToken: process.env.CF_API_TOKEN,
};

async function main() {
  const referencePath = path.join(__dirname, "test-reference.jpg");

  if (!fs.existsSync(referencePath)) {
    throw new Error("Please add test-reference.jpg to the backend folder.");
  }

  const referenceBuffer = fs.readFileSync(referencePath);

  console.log("Reference image size:", referenceBuffer.length, "bytes");

  console.log("\nTesting FLUX reference-image generation...");

  const result = await generateCloudflareImage(
    credentials,
    "Create a modern promotional graphic inspired by the reference image. Preserve its main subject, but create a fresh and professional composition.",
    {
      width: 512,
      height: 512,
      imageInputs: [
        {
          buffer: referenceBuffer,
          mimetype: "image/jpeg",
        },
      ],
    },
  );

  console.log("\nReference-image test passed!");
  console.log("Model:", result.model);
  console.log("MIME:", result.mimeType);
  console.log("Dimensions:", result.width, "x", result.height);
  console.log("Reference count:", result.referenceCount);
  console.log("Generated bytes:", result.buffer.length);
}

main().catch((error) => {
  console.error("Test failed:", error.code || error.message);
  console.error(error.message);
  process.exitCode = 1;
});
